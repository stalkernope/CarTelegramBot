def get_all_cars():

    return CARS





def get_car(name):

    if not name:

        return None


    name = str(name).lower()



    for car in CARS:


        if car["name"].lower() == name:

            return car



    return None





def search_car(text):

    text = str(text).lower()



    return [

        car

        for car in CARS

        if text in car["name"].lower()

    ]







def get_by_class(car_class):


    return [

        car

        for car in CARS

        if car["class"] == car_class

    ]







def get_by_rarity(rarity):


    return [

        car

        for car in CARS

        if car["rarity"] == rarity

    ]







def get_shop_cars():


    return [

        car

        for car in CARS

        if car["locked"] == False

    ]



